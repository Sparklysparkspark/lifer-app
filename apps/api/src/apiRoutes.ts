/** Fastify's rewriteUrl: /api/v1/... is the versioned name of /api/..., so one set of handlers
 *  answers both and hooks still see /api/... in request.url. */
export function apiVersionAlias(req: { url?: string }): string {
  return (req.url ?? "/").replace(/^\/api\/v1(?=[/?]|$)/, "/api");
}

