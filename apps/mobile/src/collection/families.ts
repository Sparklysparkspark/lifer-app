/** The section a species falls in under Group > Family group: a locale key, or a plain family name. */
export function familyGroup(taxonClass: string | null, family: string | null): { key: string } | { name: string } {
  if (family && taxonClass === "aves" && BIRD_FAMILY_GROUPS[family]) return { key: BIRD_FAMILY_GROUPS[family] };
  return family ? { name: family } : { key: "familyGroups.other" };
}
