// Embeds the reference-photo kind prompts with the CLIP text encoder once and writes them to
// packages/core/src/species/portraitPromptVectors.ts, so scoring photos needs no text model.
// Rerun only when the prompts or the CLIP model change (then clear the stored scores).
//
// Usage (the CLIP text model must be downloaded under APP_DATA_DIR/models):
//   APP_DATA_DIR=... npx tsx packages/data-pipeline/src/scripts/build-portrait-prompt-vectors.ts
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { embedTextVectors, TEXT_MODEL_VERSION } from "@lifer/core/species/textEmbedding.js";

// "portrait" covers every group in the catalog, shells included: a shell is how most mollusks are
// identified. A photo's kind is the best-matching prompt's kind.
const PROMPTS: Record<string, string[]> = {
  portrait: [
    "a photo of a bird",
    "a photo of an animal",
    "a wildlife photograph",
    "a photo of a mammal",
    "a photo of a fish",
    "a photo of a frog",
    "a photo of a lizard",
    "a photo of a snake",
    "a photo of a turtle",
    "a photo of a crab",
    "a photo of a sea snail",
    "a photo of a seashell",
    "a photo of a sea slug",
    "a photo of a starfish",
    "a photo of a coral",
    "a photo of a sponge",
    "a photo of an octopus",
    "a photo of a jellyfish",
    "a photo of a sea anemone",
    "an underwater photo of a fish",
    "a photo of a snail shell",
    "a photo of a clam shell",
    "a photo of seashells on a plain background",
    "a photo of a bat",
    "a photo of a salamander",
    "a photo of a bird perched on a branch",
    "a photo of a shrimp",
  ],
  egg: ["a photo of eggs", "a clutch of eggs in a nest", "bird eggs on the ground", "a photo of frog spawn"],
  nest: ["a photo of an empty bird nest", "a bird nest"],
  tracks: ["animal footprints in mud", "animal tracks in the snow"],
  scat: ["animal droppings on the ground", "a pile of animal scat"],
  bones: ["an animal skull", "animal bones", "a skeleton"],
  specimen: [
    "a dead animal",
    "a museum specimen in a drawer",
    "a preserved specimen in a jar",
    "a stuffed bird specimen with a label",
    "a dead fish on a table",
    "roadkill",
  ],
  habitat: ["a landscape photo with no animals", "a photo of a forest", "a photo of a river", "a photo of a beach"],
  map: ["a range map", "a distribution map of a species", "a map"],
  drawing: [
    "a drawing of an animal",
    "a painting of a bird",
    "a scientific illustration",
    "a black and white line drawing",
  ],
  text: ["a page of text", "a chart", "a diagram", "a spectrogram", "a table of text"],
};

async function main() {
  const prompts = Object.entries(PROMPTS).flatMap(([kind, texts]) => texts.map((text) => [kind, text] as const));
  const vectors = await embedTextVectors(
    prompts.map(([, text]) => text),
    "background",
  );
  // int8 with one scale per vector: a quarter of float32's size, and the rounding error moves a
  // similarity by well under a thousandth.
  const dim = vectors[0].length;
  const bytes = new Int8Array(prompts.length * dim);
  const scales = vectors.map((v, i) => {
    const scale = Math.max(...Array.from(v, Math.abs)) / 127;
    for (let k = 0; k < dim; k++) bytes[i * dim + k] = Math.round(v[k] / scale);
    return Number(scale.toPrecision(6));
  });
  const out = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    "../../../core/src/species/portraitPromptVectors.ts",
  );
  writeFileSync(
    out,
    `// Generated by packages/data-pipeline/src/scripts/build-portrait-prompt-vectors.ts; do not edit.
export const PROMPT_TEXT_MODEL_VERSION = ${JSON.stringify(TEXT_MODEL_VERSION)};
export const PROMPT_DIM = ${dim};
export const PROMPTS: ReadonlyArray<readonly [kind: string, text: string]> = ${JSON.stringify(prompts, null, 2)};
export const PROMPT_SCALES: readonly number[] = ${JSON.stringify(scales)};
export const PROMPT_VECTORS_INT8 =
  ${JSON.stringify(Buffer.from(bytes.buffer).toString("base64"))};
`,
  );
  console.log(`[portrait-prompts] wrote ${prompts.length} prompt vectors to ${out}`);
  // The text model's native bindings crash on a normal teardown; everything is written by now.
  process.exit(0);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
