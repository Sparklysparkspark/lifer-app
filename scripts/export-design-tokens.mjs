#!/usr/bin/env node
// Writes packages/shared/src/designTokens.ts from apps/web/src/theme.css so the phone app and the
// web app share one set of colours, radii, spacing and type. --check fails when the file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cssPath = join(root, "apps", "web", "src", "theme.css");
const outPath = join(root, "packages", "shared", "src", "designTokens.ts");

/** The declarations (`--name: value`) of the first block opened by `selector`. */
function block(css, selector) {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`theme.css has no ${selector} block`);
  const end = css.indexOf("}", start);
  return [
    ...css
      .slice(start, end)
      .replace(/\/\*[\s\S]*?\*\//g, "")
      .matchAll(/(--[\w-]+):\s*([^;]+);/g),
  ].map((m) => [m[1], m[2].trim()]);
}

// 1rem is 16px; a unitless or calc() line height is evaluated to a ratio.
function px(value) {
  const m = /^(-?[\d.]+)rem$/.exec(value);
  if (!m) throw new Error(`Expected a rem size, got "${value}"`);
  return Number(m[1]) * 16;
}
function ratio(value) {
  const m = /^calc\(([\d.]+)\s*\/\s*([\d.]+)\)$/.exec(value);
  return m ? Number(m[1]) / Number(m[2]) : Number(value);
}

export function buildTokens(css) {
  const colors = (sel) => Object.fromEntries(block(css, sel).map(([k, v]) => [k.replace("--color-", ""), v]));
  const theme = block(css, "@theme");
  const group = (prefix) =>
    Object.fromEntries(
      theme
        .filter(([k]) => k.startsWith(prefix) && !k.includes("--line-height"))
        .map(([k, v]) => [k.slice(prefix.length), px(v)]),
    );
  const type = {};
  for (const [k, v] of theme) {
    // Letter spacing and weight are web-only refinements; the phone app takes size and line height.
    if (!k.startsWith("--text-") || /--(letter-spacing|font-weight)$/.test(k)) continue;
    const m = /^--text-([\w-]+?)(--line-height)?$/.exec(k);
    type[m[1]] ??= {};
    type[m[1]][m[2] ? "lineHeight" : "size"] = m[2] ? ratio(v) : px(v);
  }
  return {
    light: colors(":root"),
    dark: colors(".dark"),
    spacing: group("--spacing-"),
    radius: group("--radius-"),
    type,
  };
}

export function render(tokens) {
  return `// Generated by scripts/export-design-tokens.mjs from apps/web/src/theme.css. Do not edit.
// Sizes are pixels; line heights are ratios.
export const designTokens = ${JSON.stringify(tokens, null, 2)} as const;
`;
}

const generate = () => render(buildTokens(readFileSync(cssPath, "utf8")));

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = generate();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(outPath, "utf8");
    } catch {
      // A missing file is stale too.
    }
    if (current !== next) {
      console.error("designTokens.ts is out of date with theme.css. Run: npm run export:design-tokens");
      process.exit(1);
    }
  } else writeFileSync(outPath, next);
}
