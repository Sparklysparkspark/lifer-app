#!/usr/bin/env node
// Writes docs/docs/guides/keyboard-shortcuts.md from the keyboard registry (apps/web/src/lib/keymap.ts)
// and the sheet's names (apps/web/src/locales/en.json), so the page cannot drift. `--check` fails
// when the page is out of date; run without it to rewrite the page (npm run gen:shortcuts-doc).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "docs", "docs", "guides", "keyboard-shortcuts.md");
const en = JSON.parse(readFileSync(join(root, "apps/web/src/locales/en.json"), "utf8"));

// Where each group of keys applies, in page order. Dialogs come last; widget keys are the platform's own.
const SCOPES = ["global", "gallery", "photo", "video", "import", "review", "map", "dialog"];

const NAMES = {
  ArrowRight: "→",
  ArrowLeft: "←",
  ArrowUp: "↑",
  ArrowDown: "↓",
  Escape: "Esc",
  " ": "Space",
  Enter: "Enter",
  Backspace: "Backspace",
  Delete: "Delete",
  Tab: "Tab",
  Home: "Home",
  End: "End",
};
const isCodeToken = (k) => /^(Digit\d|Numpad\d|Bracket(Left|Right))$/.test(k);

/** Same labels as chordLabel() in keymap.ts. */
export function chordLabel(chord, mac) {
  const key = chord.endsWith("++") || chord === "+" ? "+" : chord.split("+").pop();
  const mods = chord === "+" ? [] : chord.split("+").slice(0, key === "+" ? -2 : -1);
  const shown = isCodeToken(key) ? key.replace(/^(Digit|Numpad)/, "") : (NAMES[key] ?? key.toUpperCase());
  if (mac) {
    return (
      (mods.includes("Ctrl") ? "⌃" : "") +
      (mods.includes("Alt") ? "⌥" : "") +
      (mods.includes("Shift") ? "⇧" : "") +
      (mods.includes("Mod") ? "⌘" : "") +
      shown
    );
  }
  return [...new Set(mods.map((m) => (m === "Mod" ? "Ctrl" : m))), shown].join("+");
}

/** The KEYMAP entries as { id, scope, chords, mac, desktopOnly }, read from the source text. */
export function parseKeymap(text) {
  const start = text.indexOf("export const KEYMAP");
  const body = text.slice(start, text.indexOf("\n};", start));
  const list = (s) => [...s.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((m) => m[1].replace(/\\(.)/g, "$1"));
  const re =
    /(\w+):\s*\{\s*scope:\s*"(\w+)",\s*chords:\s*\[([^\]]*)\](?:,\s*mac:\s*\[([^\]]*)\])?(,\s*desktopOnly:\s*true)?/g;
  const found = [...body.matchAll(re)];
  // A new entry shape the pattern misses must fail loudly, not vanish from the page.
  if (found.length !== (body.match(/scope:/g) ?? []).length)
    throw new Error("keymap.ts has an entry the generator cannot read");
  return found.map((m) => ({
    id: m[1],
    scope: m[2],
    chords: list(m[3]),
    mac: m[4] === undefined ? null : list(m[4]),
    desktopOnly: !!m[5],
  }));
}

const NAV = { page1: "collection", page2: "gallery", page3: "map", page4: "albums", page5: "stats" };
const actionName = (id) => (NAV[id] ? `Go to ${en.nav[NAV[id]]}` : en.shortcuts.action[id]);

export function render(entries) {
  const lines = [
    "---",
    "title: Keyboard shortcuts",
    "description: Every keyboard shortcut in Lifer, by screen, for Mac, Windows and Linux.",
    "---",
    "",
    "# Keyboard shortcuts",
    "",
    "<!-- Generated by scripts/gen-shortcuts-doc.mjs from apps/web/src/lib/keymap.ts. Do not edit. -->",
    "",
    "Press <kbd>?</kbd> in Lifer to see these in the app. Lifer follows Lightroom's keys where Lightroom has one.",
    "",
    "Mac keys are shown first. On Windows and Linux, <kbd>Cmd</kbd> (⌘) becomes <kbd>Ctrl</kbd>, <kbd>Option</kbd> (⌥) becomes <kbd>Alt</kbd>, and <kbd>Shift</kbd> (⇧) stays the same.",
    "",
    "Keys that work only in the desktop app are marked (desktop app). Letter keys and digits do nothing while you are typing in a field.",
    "",
  ];
  for (const scope of SCOPES) {
    const rows = entries.filter((e) => e.scope === scope && e.chords.length > 0);
    if (rows.length === 0) continue;
    lines.push(`## ${en.shortcuts.scope[scope]}`, "", "| Action | Mac | Windows and Linux |", "| --- | --- | --- |");
    for (const e of rows) {
      const cell = (mac) => (mac && e.mac ? e.mac : e.chords).map((c) => `\`${chordLabel(c, mac)}\``).join(" or ");
      lines.push(`| ${actionName(e.id)}${e.desktopOnly ? " (desktop app)" : ""} | ${cell(true)} | ${cell(false)} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

export async function build() {
  const entries = parseKeymap(readFileSync(join(root, "apps/web/src/lib/keymap.ts"), "utf8"));
  const config = (await resolveConfig(OUT)) ?? {};
  return format(render(entries), { ...config, parser: "markdown" });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = await build();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch {
      // Missing page: reported below.
    }
    if (current !== next) {
      console.error(
        "docs/docs/guides/keyboard-shortcuts.md is out of date with keymap.ts. Run: npm run gen:shortcuts-doc",
      );
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, next);
    console.log("Wrote docs/docs/guides/keyboard-shortcuts.md");
  }
}
